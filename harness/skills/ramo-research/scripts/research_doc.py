#!/usr/bin/env python3
# 리서치 주제 문서 검사·색인·렌더러: docs/research/<topic>/README.md 계약 검사, _overview.md 표 생성, 요청 시 HTML
"""Research topic checker, overview indexer, and renderer (stdlib only, python >= 3.9).

A research topic is one folder `docs/research/<topic>/` whose `README.md` is the whole committed
deliverable: a short, human-first account of one model or codebase (kind `subject`), of one
service's flow, operating policy, and history (kind `service`), or a comparison of several
external cases (kind `cases`), with a `## 출처` table pointing at the original sources.
Detailed per-source reading stays in `.ramo/research/`, which is volatile and never committed.

  check  <topic-dir> [--final]          contract check of one topic, exit 1 on any ERROR
  index  <research-dir> [--check]       rewrite the topic table in `_overview.md` from every
                                        topic's frontmatter (--check: exit 1 when it is stale)
  render <topic-dir> [--out X]          one self-contained HTML copy of the README

`check` is the mechanical half of `.claude/rules/workflow/00-research.md`: it can see that a
section, a source link, a depth, or a source reference is present, and it cannot see whether
any of them is true. Without `--final` a `status: draft` topic is checked for frontmatter and
sources only.

`index` exists so that several people can research in parallel without editing the same
lines. Each person writes only inside their own topic folder; the overview table is derived,
one row per topic sorted by folder name, and the skill marks `_overview.md` `merge=union` in
`.gitattributes`, so two concurrent new rows merge without a conflict and the next `index`
run restores the order.

`render` escapes every byte of document text and only emits links whose scheme is http, https,
mailto, a fragment, or relative. Topic documents quote pages fetched from the open web, so the
renderer is a place where a hostile page could otherwise put script into a file a teammate
opens in a browser. Raw HTML in the markdown is therefore shown as text, never passed through.

stdlib-only for the same reason the hook handlers are
(.claude/rules/workflow/08-hook-conventions.md): this file is seeded into every consumer
repository and cannot assume a virtualenv.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

TOPIC_TYPE = "Research Topic"
TOPIC_FILE = "README.md"
OVERVIEW_FILE = "_overview.md"
CATEGORY = "research"
KINDS = ("subject", "service", "cases")
KIND_LABELS = {"subject": "모델·코드 분석", "service": "서비스·정책 분석", "cases": "사례 비교"}
STATUS_VALUES = ("draft", "stable", "deprecated")
DEPTH_VALUES = ("full", "partial", "abstract-only", "failed")
REQUIRED = (
    "type",
    "title",
    "kind",
    "summary",
    "category",
    "status",
    "created",
    "updated",
    "tags",
    "generated",
)
SECTIONS = {
    "subject": ("전체 아키텍처", "피처와 타깃", "학습 방법", "주의사항", "출처"),
    "service": ("전체 흐름", "운영 정책", "변경 이력", "주의사항", "출처"),
    "cases": ("사례 비교", "사례 요약", "주의사항", "출처"),
}
SOURCE_COLUMNS = ("id", "유형", "제목", "링크·경로", "읽은 깊이")
LENGTH_BASELINE = 200
INDEX_BEGIN = "<!-- research-index:begin (generated by research_doc.py index; do not edit) -->"
INDEX_END = "<!-- research-index:end -->"
INDEX_HEADER = "| 주제 | 종류 | 한 줄 요약 | 상태 | 갱신 | 출처 |\n|---|---|---|---|---|---|"

ID_RE = re.compile(r"^s\d{2}$")
SOURCE_REF_RE = re.compile(r"(?<![\w/.-])(s\d{2})(?![\w])")
HOME_PATH_RE = re.compile(r"(?<![\w.])(?:/Users/|/home/|~/|[A-Za-z]:\\Users\\)")
PLACEHOLDER_RE = re.compile(r"<(?!https?:|mailto:|!--)[^<>\n]*\s[^<>\n]*>")
FM_PLACEHOLDER_RE = re.compile(r"<[^<>\n]+>")
FENCE_RE = re.compile(r"^\s*(```|~~~)")
KEY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$")
LIST_RE = re.compile(r"^(\s*)([-*]|\d+\.)\s+(.*)$")
PARA_STOP_RE = re.compile(r"^(#{1,6}\s|\||>|[-*]\s|\d+\.\s|\[\^)")
FOOTNOTE_REF_RE = re.compile(r"\[\^([A-Za-z0-9_-]+)\](?!:)")
FOOTNOTE_DEF_RE = re.compile(r"^\[\^([A-Za-z0-9_-]+)\]:\s*(.*)$")
SAFE_SCHEME_RE = re.compile(r"^(?:https?:|mailto:|#|[^:]*$)", re.I)


# ------------------------------------------------------------------- parsing


def unquote(value: str) -> str:
    """Strip surrounding whitespace and one layer of YAML quotes."""
    return value.strip().strip('"').strip("'")


def split_frontmatter(text: str):
    """Return (frontmatter lines, body, error). Narrow YAML subset, mirrors wiki_runtime.py."""
    if not text.startswith("---\n"):
        return [], text, "no frontmatter block (the file must start with '---')"
    end = text.find("\n---", 4)
    if end == -1:
        return [], text, "frontmatter block is not closed with a second '---'"
    return text[4:end].split("\n"), text[end + 4 :].lstrip("\n"), None


def _parse_block_list(lines: list, i: int) -> tuple:
    """Parse `  - item` lines (scalars or small dicts) starting at i; return (items, next i)."""
    items = []
    while i < len(lines) and lines[i].startswith("  - "):
        head = lines[i][4:]
        i += 1
        dm = KEY_RE.match(head)
        if not dm:
            items.append(unquote(head))
            continue
        item = {dm.group(1): unquote(dm.group(2))}
        while i < len(lines) and lines[i].startswith("    "):
            sm = KEY_RE.match(lines[i].strip())
            if not sm:
                break
            item[sm.group(1)] = unquote(sm.group(2))
            i += 1
        items.append(item)
    return items, i


def parse_frontmatter(lines: list) -> tuple:
    """Scalars, `key: []`, flow mappings kept as raw strings, and block lists of scalars or of
    small dicts. Returns (data, errors)."""
    data: dict = {}
    errors = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.lstrip().startswith("#"):
            i += 1
            continue
        m = KEY_RE.match(line)
        if not m:
            errors.append(f"unparsable frontmatter line: {line!r}")
            i += 1
            continue
        key, inline = m.group(1), m.group(2).strip()
        i += 1
        if inline == "[]":
            data[key] = []
        elif inline:
            data[key] = unquote(inline)
        else:
            data[key], i = _parse_block_list(lines, i)
    return data, errors


def load(path: Path) -> tuple:
    """Read a document; return (frontmatter, body, errors)."""
    fm_lines, body, err = split_frontmatter(path.read_text(encoding="utf-8"))
    if err:
        return {}, body, [err]
    fm, errors = parse_frontmatter(fm_lines)
    return fm, body, errors


def iter_unfenced(body: str):
    """Yield (line, in_fence) so heading and placeholder checks skip code blocks."""
    in_fence = False
    for line in body.split("\n"):
        if FENCE_RE.match(line):
            in_fence = not in_fence
            yield line, True
            continue
        yield line, in_fence


def strip_comments(body: str) -> str:
    """Drop HTML comments -- the templates' authoring notes live in them."""
    return re.sub(r"<!--.*?-->", "", body, flags=re.S)


def sections(body: str) -> dict:
    """Map each `## heading` to its content lines (fenced blocks kept verbatim)."""
    out: dict = {}
    current = None
    for line, in_fence in iter_unfenced(strip_comments(body)):
        if not in_fence and line.startswith("## "):
            current = line[3:].strip()
            out[current] = []
        elif current is not None:
            out[current].append(line)
    return out


def table_cells(row: str) -> list:
    """Split one markdown table row into stripped cells."""
    return [cell.strip() for cell in row.strip().strip("|").split("|")]


# ------------------------------------------------------------------- checks


class Report:
    """Collected ERROR and WARN lines for one check run."""

    def __init__(self):
        self.errors = []
        self.warnings = []

    def error(self, path: Path, msg: str):
        """Record a contract violation (makes the run exit 1)."""
        self.errors.append(f"ERROR {path}: {msg}")

    def warn(self, path: Path, msg: str):
        """Record a finding that does not fail the run."""
        self.warnings.append(f"WARN {path}: {msg}")


def check_fields(path: Path, fm: dict, rep: Report):
    """Required keys, document type, kind, category, status, and unfilled placeholders."""
    for key in REQUIRED:
        if key not in fm or fm[key] in ("", []):
            rep.error(path, f"frontmatter field missing or empty: {key}")
    if fm.get("type") and fm["type"] != TOPIC_TYPE:
        rep.error(path, f"type must be '{TOPIC_TYPE}', got '{fm['type']}'")
    if fm.get("kind") and fm["kind"] not in KINDS:
        rep.error(path, f"kind '{fm['kind']}' outside {'/'.join(KINDS)}")
    if fm.get("category") and fm["category"] != CATEGORY:
        rep.error(path, f"category must be '{CATEGORY}'")
    if fm.get("status") and fm["status"] not in STATUS_VALUES:
        rep.error(path, f"status '{fm['status']}' outside {'/'.join(STATUS_VALUES)}")
    for key, value in fm.items():
        if isinstance(value, str) and FM_PLACEHOLDER_RE.search(value):
            rep.error(path, f"unfilled template placeholder in frontmatter field {key}")


def check_text(path: Path, fm: dict, body: str, rep: Report):
    """Home-directory paths anywhere; heading depth and placeholders outside code; length."""
    clean = strip_comments(body)
    if HOME_PATH_RE.search(clean + "\n" + "\n".join(str(v) for v in fm.values())):
        rep.error(path, "absolute local path found; cite the canonical identifier (SOT-1)")
    for line, in_fence in iter_unfenced(clean):
        if in_fence:
            continue
        if re.match(r"^#{3,6}\s", line):
            rep.error(path, f"heading deeper than '##' (doc-readability R3): {line.strip()}")
        elif PLACEHOLDER_RE.search(line):
            rep.warn(path, f"possible unfilled placeholder: {line.strip()[:80]}")
    lines = clean.strip().count("\n") + 1
    if lines > LENGTH_BASELINE:
        rep.warn(path, f"{lines} lines, over the {LENGTH_BASELINE}-line baseline: split the topic?")


def check_location_cells(path: Path, secs: dict, rep: Report):
    """Every table with a `위치` column fills it on every row."""
    for name, lines in secs.items():
        if name == "출처":
            continue
        table = []
        for line, in_fence in iter_unfenced("\n".join(lines)):
            if line.strip().startswith("|") and not in_fence:
                table.append(line)
            elif table:
                check_location_table(path, name, table, rep)
                table = []
        if table:
            check_location_table(path, name, table, rep)


def check_location_table(path: Path, section: str, table: list, rep: Report):
    """One table: when its header has `위치`, no data row may leave that cell empty."""
    header = table_cells(table[0])
    if "위치" not in header:
        return
    col = header.index("위치")
    for row in table[2:]:
        cells = table_cells(row)
        if col >= len(cells) or not cells[col] or cells[col] in ("-", "—"):
            rep.error(path, f"'{section}' row with an empty 위치 cell: {row.strip()[:70]}")


def check_sources(path: Path, secs: dict, rep: Report) -> list:
    """Validate the `## 출처` table; return its source ids in order."""
    table = [line for line in secs.get("출처", []) if line.strip().startswith("|")]
    if len(table) < 2:
        rep.error(path, "'출처' needs a table with at least one source")
        return []
    header = table_cells(table[0])
    missing = [c for c in SOURCE_COLUMNS if c not in header]
    if missing:
        rep.error(path, f"'출처' table is missing columns: {', '.join(missing)}")
        return []
    col = {c: header.index(c) for c in SOURCE_COLUMNS}
    ids = []
    for row in table[2:]:
        cells = table_cells(row) + [""] * len(header)
        sid, link, depth = cells[col["id"]], cells[col["링크·경로"]], cells[col["읽은 깊이"]]
        if not ID_RE.match(sid):
            rep.error(path, f"source id '{sid}' must look like s01")
            continue
        if sid in ids:
            rep.error(path, f"duplicate source id '{sid}'")
        if not link or link in ("-", "—"):
            rep.error(path, f"source {sid} has no 링크·경로")
        if depth not in DEPTH_VALUES:
            rep.error(path, f"source {sid} depth '{depth}' outside {'/'.join(DEPTH_VALUES)}")
        ids.append(sid)
    if not ids:
        rep.error(path, "'출처' table has no source rows")
    return ids


def check_source_refs(path: Path, secs: dict, source_ids: list, rep: Report):
    """Every `sNN` the body cites is a listed source; an uncited source is only a warning."""
    cited = set()
    for name, lines in secs.items():
        if name == "출처":
            continue
        cited |= set(SOURCE_REF_RE.findall("\n".join(lines)))
    for ref in sorted(cited - set(source_ids)):
        rep.error(path, f"body cites {ref}, which is not in the '출처' table")
    for sid in source_ids:
        if sid not in cited:
            rep.warn(path, f"source {sid} is listed but never cited in the body")


def check_folder(topic_dir: Path, rep: Report):
    """A topic folder holds its README and rendered HTML copies, nothing else."""
    for child in sorted(topic_dir.iterdir()):
        if child.is_dir():
            rep.error(child, "topic folders are flat; no subdirectories")
        elif child.name != TOPIC_FILE and child.suffix != ".html":
            rep.warn(child, "unexpected file in a topic folder (README.md and *.html only)")


def check_topic(topic_dir: Path, final: bool) -> Report:
    """Check one topic folder against the research contract."""
    rep = Report()
    readme = topic_dir / TOPIC_FILE
    if not readme.is_file():
        rep.error(readme, "topic README.md not found")
        return rep
    fm, body, errors = load(readme)
    for err in errors:
        rep.error(readme, err)
    if not fm:
        return rep
    check_fields(readme, fm, rep)
    check_text(readme, fm, body, rep)
    check_folder(topic_dir, rep)
    secs = sections(body)
    source_ids = check_sources(readme, secs, rep)
    if final or fm.get("status") != "draft":
        for name in SECTIONS.get(fm.get("kind"), ()):
            if name not in secs:
                rep.error(readme, f"required section missing: ## {name}")
        check_location_cells(readme, secs, rep)
        check_source_refs(readme, secs, source_ids, rep)
    return rep


# ------------------------------------------------------------------- overview index


def index_rows(research_dir: Path) -> list:
    """One table row per topic folder that has a readable README, sorted by folder name."""
    rows = []
    for topic_dir in sorted(p for p in research_dir.iterdir() if p.is_dir()):
        fm, body, errors = (
            load(topic_dir / TOPIC_FILE) if (topic_dir / TOPIC_FILE).is_file() else ({}, "", [])
        )
        if not fm or errors:
            continue
        n_sources = len(
            [
                line
                for line in sections(body).get("출처", [])
                if re.match(r"^\|\s*s\d{2}\s*\|", line.strip())
            ]
        )
        cells = (
            f"[{fm.get('title', topic_dir.name)}]({topic_dir.name}/{TOPIC_FILE})",
            KIND_LABELS.get(fm.get("kind", ""), fm.get("kind", "")),
            fm.get("summary", ""),
            fm.get("status", ""),
            fm.get("updated", ""),
            str(n_sources),
        )
        rows.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
    return rows


def build_index(overview_text: str, rows: list) -> str:
    """Replace the generated block between the index markers; raise when markers are absent."""
    begin, end = overview_text.find(INDEX_BEGIN), overview_text.find(INDEX_END)
    if begin == -1 or end == -1 or end < begin:
        raise ValueError(f"{OVERVIEW_FILE} has no research-index markers")
    block = "\n".join([INDEX_BEGIN, INDEX_HEADER, *rows, INDEX_END])
    return overview_text[:begin] + block + overview_text[end + len(INDEX_END) :]


def index(research_dir: Path, check_only: bool) -> int:
    """Regenerate (or, with check_only, verify) the topic table in `_overview.md`."""
    overview = research_dir / OVERVIEW_FILE
    if not overview.is_file():
        print(f"ERROR {overview}: not found; create it from templates/overview.md")
        return 1
    current = overview.read_text(encoding="utf-8")
    try:
        updated = build_index(current, index_rows(research_dir))
    except ValueError as exc:
        print(f"ERROR {overview}: {exc}")
        return 1
    if check_only:
        if updated != current:
            print(f"ERROR {overview}: topic table is stale; run research_doc.py index")
            return 1
        print("research_doc index: up to date")
        return 0
    overview.write_text(updated, encoding="utf-8")
    print(f"research_doc index: wrote {overview} ({updated.count(chr(10) + '| [')} topics)")
    return 0


# ------------------------------------------------------------------- rendering


def slug(text: str) -> str:
    """Heading text to an anchor id (Hangul kept)."""
    s = re.sub(r"[^\w\s-]", "", text, flags=re.U).strip().lower()
    return re.sub(r"[\s_]+", "-", s) or "section"


class Renderer:
    """Markdown subset to escaped HTML: headings, paragraphs, lists, tables, fences, quotes,
    footnotes, links, code spans, bold, italic. Nothing else passes through.

    `footnotes` and `toc` are collected only while they are lists (the top-level pass); inner
    blocks render with both set to None.
    """

    def __init__(self):
        self.footnotes = None
        self.toc = None
        self.prefix = ""

    def href(self, raw: str):
        """Safe link target for an escaped URL, or None when its scheme is not allowed."""
        url = html.unescape(raw)
        if not SAFE_SCHEME_RE.match(url):
            return None
        return url

    def _inline_text(self, part: str) -> str:
        """Escape, then apply footnote, link, autolink, bold, and italic patterns."""

        def footnote(m):
            return f'<sup class="fn"><a href="#fn-{m.group(1)}">{m.group(1)}</a></sup>'

        def link(m):
            target = self.href(m.group(2))
            if target is None:
                return m.group(1)
            return f'<a href="{html.escape(target, quote=True)}">{m.group(1)}</a>'

        def autolink(m):
            return f'<a href="{m.group(1)}">{m.group(1)}</a>'

        s = FOOTNOTE_REF_RE.sub(footnote, html.escape(part))
        s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, s)
        s = re.sub(r"&lt;(https?://[^\s&]+)&gt;", autolink, s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        return re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", s)

    def inline(self, text: str) -> str:
        """Render inline markdown; code spans are escaped verbatim and never transformed."""
        out = []
        for part in re.split(r"(`[^`]*`)", text):
            if len(part) >= 2 and part.startswith("`") and part.endswith("`"):
                out.append(f"<code>{html.escape(part[1:-1])}</code>")
            else:
                out.append(self._inline_text(part))
        return "".join(out)

    def _table(self, lines: list, i: int) -> tuple:
        rows = []
        while i < len(lines) and lines[i].strip().startswith("|"):
            rows.append(lines[i])
            i += 1
        head = "".join(f"<th>{self.inline(c)}</th>" for c in table_cells(rows[0]))
        body = "".join(
            "<tr>" + "".join(f"<td>{self.inline(c)}</td>" for c in table_cells(r)) + "</tr>"
            for r in rows[2:]
        )
        table = f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"
        return f'<div class="table-wrap">{table}</div>', i

    def _fence(self, lines: list, i: int) -> tuple:
        code = []
        i += 1
        while i < len(lines) and not FENCE_RE.match(lines[i]):
            code.append(lines[i])
            i += 1
        return f"<pre><code>{html.escape(chr(10).join(code))}</code></pre>", i + 1

    def _heading(self, level: int, title: str) -> str:
        anchor = self.prefix + slug(title)
        if level == 2 and self.toc is not None:
            self.toc.append((anchor, title))
        return f'<h{level} id="{anchor}">{self.inline(title)}</h{level}>'

    def _quote(self, lines: list, i: int) -> tuple:
        quote = []
        while i < len(lines) and lines[i].strip().startswith(">"):
            quote.append(re.sub(r"^\s*>\s?", "", lines[i]))
            i += 1
        return f"<blockquote>{self._nested(chr(10).join(quote))}</blockquote>", i

    @staticmethod
    def _list_items(lines: list, i: int) -> tuple:
        """Collect top-level items with their dedented continuation lines."""
        items = []
        while i < len(lines):
            cur = LIST_RE.match(lines[i])
            indented = lines[i].startswith((" ", "\t"))
            if cur and not cur.group(1):
                items.append([cur.group(3)])
            elif indented and lines[i].strip() and items:
                items[-1].append(re.sub(r"^( {1,4}|\t)", "", lines[i]))
            elif (
                not lines[i].strip()
                and items
                and i + 1 < len(lines)
                and lines[i + 1].startswith((" ", "\t"))
            ):
                items[-1].append("")
            else:
                break
            i += 1
        return items, i

    def _list(self, lines: list, i: int) -> tuple:
        tag = "ol" if LIST_RE.match(lines[i]).group(2)[0].isdigit() else "ul"
        items, i = self._list_items(lines, i)
        rendered = []
        for item in items:
            first, rest = item[0], "\n".join(item[1:])
            inner = self.inline(first)
            if rest.strip():
                if LIST_RE.match(rest.strip().split("\n", maxsplit=1)[0]):
                    inner += self._nested(rest)
                else:
                    inner = self.inline(first + " " + " ".join(rest.split()))
            rendered.append(f"<li>{inner}</li>")
        return f"<{tag}>{''.join(rendered)}</{tag}>", i

    def _paragraph(self, lines: list, i: int) -> tuple:
        para = []
        while (
            i < len(lines)
            and lines[i].strip()
            and not FENCE_RE.match(lines[i])
            and not PARA_STOP_RE.match(lines[i].strip())
        ):
            para.append(lines[i].strip())
            i += 1
        if not para:  # a line no other rule claimed; emit it alone rather than loop
            para.append(lines[i].strip())
            i += 1
        return f"<p>{self.inline(' '.join(para))}</p>", i

    def _nested(self, text: str) -> str:
        """Render an inner block (list item, quote) without touching the TOC or footnotes."""
        saved = (self.footnotes, self.toc)
        self.footnotes, self.toc = None, None
        try:
            return self.blocks(text, self.prefix)
        finally:
            self.footnotes, self.toc = saved

    def _block(self, lines: list, i: int) -> tuple:  # pylint: disable=too-many-return-statements
        """Render the block starting at line i; return (html, next i).

        One early return per block kind: the order is the precedence, read top to bottom.
        """
        line = lines[i]
        stripped = line.strip()
        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        footnote = FOOTNOTE_DEF_RE.match(line)
        bullet = LIST_RE.match(line)
        if FENCE_RE.match(line):
            return self._fence(lines, i)
        if heading:
            return self._heading(len(heading.group(1)), heading.group(2).strip()), i + 1
        if re.match(r"^(-{3,}|\*{3,})$", stripped):
            return "<hr>", i + 1
        if footnote and self.footnotes is not None:
            self.footnotes.append((footnote.group(1), footnote.group(2)))
            return "", i + 1
        if (
            stripped.startswith("|")
            and i + 1 < len(lines)
            and re.match(r"^\s*\|?\s*:?-{2,}", lines[i + 1])
        ):
            return self._table(lines, i)
        if stripped.startswith(">"):
            return self._quote(lines, i)
        if bullet and not bullet.group(1):
            return self._list(lines, i)
        return self._paragraph(lines, i)

    def blocks(self, text: str, prefix: str = "") -> str:
        """Render a markdown block sequence; heading anchors get `prefix`."""
        self.prefix = prefix
        lines = strip_comments(text).split("\n")
        out = []
        i = 0
        while i < len(lines):
            if not lines[i].strip():
                i += 1
                continue
            piece, i = self._block(lines, i)
            if piece:
                out.append(piece)
        return "\n".join(out)


