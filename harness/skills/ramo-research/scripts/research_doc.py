def main(argv=None) -> int:
    """CLI entry point: `check`, `index`, or `render`."""
    parser = argparse.ArgumentParser(description="Check, index, or render docs/research topics.")
    sub = parser.add_subparsers(dest="cmd", required=True)
    pc = sub.add_parser("check", help="contract check of one topic folder")
    pc.add_argument("topic_dir", type=Path)
    pc.add_argument(
        "--final", action="store_true", help="check the finished document even while draft"
    )
    pi = sub.add_parser("index", help="regenerate the topic table in _overview.md")
    pi.add_argument("research_dir", type=Path)
    pi.add_argument("--check", action="store_true", help="exit 1 when the table is stale")
    pr = sub.add_parser("render", help="write one self-contained HTML copy of the README")
    pr.add_argument("topic_dir", type=Path)
    pr.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)

    if args.cmd == "check":
        rep = check_topic(args.topic_dir, args.final)
        for line in rep.errors + rep.warnings:
            print(line)
        print(f"research_doc check: {len(rep.errors)} error(s), {len(rep.warnings)} warning(s)")
        return 1 if rep.errors else 0
    if args.cmd == "index":
        return index(args.research_dir, args.check)
    out = args.out or args.topic_dir / "README.html"
    print(f"research_doc render: wrote {render(args.topic_dir, out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
