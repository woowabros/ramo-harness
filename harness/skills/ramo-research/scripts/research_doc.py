def page_html(fm: dict, fallback_title: str, toc: list, main_html: str, source: str) -> str:
    """Wrap rendered content in the self-contained page shell."""
    title = html.escape(fm.get("title", fallback_title))
    labels = (("status", "상태"), ("updated", "갱신"), ("stale_after", "재조사 기준일"))
    meta_line = " · ".join(f"{lab} {html.escape(fm[key])}" for key, lab in labels if fm.get(key))
    toc_html = "".join(f'<li><a href="#{a}">{t}</a></li>' for a, t in toc)
    return (
        '<!doctype html>\n<html lang="ko"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f'<title>{title}</title><style>{CSS}</style></head><body><div class="wrap">'
        f'<header><h1>{title}</h1><p class="meta">{meta_line}</p></header>'
        f'<nav class="toc"><ol>{toc_html}</ol></nav><main>{main_html}</main>'
        f"<footer>{html.escape(source)} 에서 생성한 보기용 사본임. "
        "정본은 markdown 이며 이 파일을 직접 고치지 말 것.</footer>"
        "</div></body></html>\n"
    )


def render(topic_dir: Path, out: Path) -> Path:
    """Write the topic README as one self-contained HTML file."""
    readme = topic_dir / TOPIC_FILE
    fm, body, errors = load(readme)
    if errors:
        raise SystemExit(f"render: {readme}: {errors[0]}")
    r = Renderer()
    footnotes, toc = [], []
    r.footnotes, r.toc = footnotes, toc
    main_html = r.blocks(re.sub(r"^#\s+.*\n", "", strip_comments(body), count=1, flags=re.M))
    r.footnotes, r.toc = None, None
    if footnotes:
        items = "".join(
            f'<li id="fn-{fid}"><strong>{fid}</strong> {r.inline(text)}</li>'
            for fid, text in footnotes
        )
        main_html += (
            f'<section class="footnotes"><h2 id="footnotes">각주</h2><ol>{items}</ol></section>'
        )
    toc = [(anchor, r.inline(title)) for anchor, title in toc]
    out.write_text(page_html(fm, topic_dir.name, toc, main_html, readme.name), encoding="utf-8")
    return out


